"""Study Companion -- a Jan-backed tutor grounded in your own course material.

Two ways this app helps, and they are independent of each other:

1. A deterministic question bank (data/<course>/questions/*.jsonl) that needs
   no LLM at all -- always available, instant, and exactly correct because it
   was generated by plain arithmetic, not asked of a model.
2. A Jan chat + quiz-generation path that reads the lecture text sources in
   data/<course>/*.txt and answers ONLY from them, per its system prompt.

The JSONL schema (one question object per line) is documented at the top of
data/MATH1014/questions/generate.py. It is deliberately simple: a small local
model that gets asked to add more question can get one line right without
needing to produce a whole valid JSON document. `/api/quiz` asks Jan to
follow that exact schema when generating fresh questions, and appends
whatever comes back that actually parses to a `bank_jan.jsonl` file (never
overwriting the hand-verified `bank.jsonl`).
"""

