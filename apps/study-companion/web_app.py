# Jan is OpenAI-compatible. Same pattern as apps/arcade/web_app.py.
JAN_BASE = os.environ.get("JAN_BASE_URL", "http://127.0.0.1:1337/v1")
JAN_MODEL = os.environ.get("JAN_MODEL", "")
_model_cache = {"name": JAN_MODEL, "checked": 0.0}

# This app's own Jan settings (model and idle release), from the shared helper.
import sys  # noqa: E402  (after the shared folder is known)

_SHARED_DIR = shared_dir or str(APP_DIR.parent.parent / "shared")
if Path(_SHARED_DIR).is_dir() and _SHARED_DIR not in sys.path:
    sys.path.insert(0, _SHARED_DIR)
try:
    import forge_jan

    _jan = forge_jan.mount(app, "study-companion", roles=("tutor",))
except Exception as _jan_error:  # the question bank works with no Jan at all
    print(f"[study-companion] Jan settings unavailable: {_jan_error}")
    _jan = None


def _jan_model(client: httpx.Client) -> str:
    """Whichever model Jan currently has loaded, cached for a minute."""
    if JAN_MODEL:
        return JAN_MODEL
    chosen = _jan.model_for("tutor") if _jan else ""
    if chosen:
        return chosen
    now = time.time()
    if _model_cache["name"] and now - _model_cache["checked"] < 60:
        return _model_cache["name"]
    r = client.get(f"{JAN_BASE}/models", timeout=3.0)
    r.raise_for_status()
    data = r.json().get("data", [])
    if not data:
        raise RuntimeError("Jan is running but has no model loaded")
    name = data[0]["id"]
    _model_cache.update(name=name, checked=now)
    return name


@app.get("/api/status")
def status():
    out = {"backend": True, "jan": False, "model": None, "detail": ""}
    try:
        with httpx.Client() as client:
            # a model picked in this app's Jan settings is known without
            # asking Jan, so ask once that Jan is actually there
            client.get(f"{JAN_BASE}/models", timeout=3.0).raise_for_status()
            out["model"] = _jan_model(client)
            out["jan"] = True
    except Exception as e:  # noqa: BLE001 -- surfaced to the UI, not swallowed
        out["detail"] = f"{type(e).__name__}: {e}"
    return out


# ---------------------------------------------------------------- courses & sources


def _course_dirs():
    if not DATA_DIR.is_dir():
        return []
    return sorted(p.name for p in DATA_DIR.iterdir() if p.is_dir())


@app.get("/api/courses")
def courses():
    return {"courses": _course_dirs()}


def _label_from_stem(stem: str) -> str:
    return stem.replace("_", " ").replace("-", " ").strip().title()


def _course_dir(course: str) -> Path:
    """Only a folder that is really under data/ ('..' or a typed path is not)."""
    if course not in _course_dirs():
        raise HTTPException(404, f"No such course: {course}")
    return DATA_DIR / course


@app.get("/api/courses/{course}/sources")
def sources(course: str):
    d = _course_dir(course)
    out = []
    for p in sorted(d.glob("*.txt")):
        out.append(
            {"id": p.stem, "label": _label_from_stem(p.stem), "chars": p.stat().st_size}
        )
    return {"sources": out}


def _read_sources(course: str, source_ids: list[str]) -> str:
    d = _course_dir(course)
    known = {p.stem for p in d.glob("*.txt")}
    chunks = []
    for sid in source_ids:
        if sid not in known:  # also keeps '../../somewhere' out
            continue
        p = d / f"{sid}.txt"
        if not p.is_file():
            continue
        chunks.append(
            f"=== SOURCE: {_label_from_stem(sid)} ===\n{p.read_text(errors='ignore')}"
        )
    return "\n\n".join(chunks)


# ---------------------------------------------------------------- question bank (no LLM needed)


def _bank_files(course: str):
    d = DATA_DIR / course / "questions"
    if not d.is_dir():
        return []
    return sorted(d.glob("*.jsonl"))


def _load_bank(course: str, topic: str | None = None):
    rows = []
    for f in _bank_files(course):
        for line in f.read_text(errors="ignore").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue  # one bad line never breaks the whole bank
            if not isinstance(row, dict):
                continue
            if topic and str(row.get("topic") or "") != topic:
                continue
            row["_file"] = f.name
            rows.append(row)
    return rows


@app.get("/api/courses/{course}/bank")
def bank(course: str, topic: str | None = None, limit: int = 20, offset: int = 0):
    _course_dir(course)
    limit, offset = max(1, min(limit, 200)), max(0, offset)
    rows = _load_bank(course, topic)
    topics = sorted({str(r["topic"]) for r in rows if r.get("topic")})
    return {
        "total": len(rows),
        "topics": topics,
        "questions": rows[offset : offset + limit],
    }


# ---------------------------------------------------------------- chat

SYSTEM_PROMPT = """You are the Study Companion, a focused exam-prep tutor for a \
university student cramming for a timed, invigilated test tomorrow.

Ground rules, followed exactly:
1. Answer ONLY using the course material provided below in SOURCE blocks. If \
something is not covered by the material and you are not confident it is \
still correct standard mathematics for this topic, say plainly "this isn't \
in your material" rather than inventing syllabus content.
2. Always show full step-by-step working, not just a final answer -- the \
student needs to reproduce the method under exam conditions, not just \
recognise the result.
3. Keep the tone plain, direct and encouraging. No lecturing, no filler, no \
ALL CAPS, no more words than the explanation actually needs.
4. When a graph would genuinely help (asymptotes, periodic behaviour, a \
turning point), end your reply with a fenced block exactly like this so the \
app can draw a real chart -- do not describe the graph in words instead:
```plot
f(x) = <a plain-text expression in x, using + - * / ^ sin cos tan sqrt ln exp pi e abs>
domain: <xmin>,<xmax>
```
Only include one plot block, only when it adds real value, and only with an \
expression you are confident is exactly the function under discussion.
5. If asked to generate quiz questions, output STRICT JSON LINES, one \
question object per line, each shaped exactly like:
{"topic": "<t1..t6>", "skill": "<short-kebab-tag>", "question": "...", \
"steps": ["...", "..."], "answer": "..."}
Nothing before or after the JSON lines -- no prose, no markdown fences.

Course material follows.
"""


def _call_jan(client: httpx.Client, messages: list[dict], max_tokens: int = 900) -> str:
    body = {"messages": messages, "temperature": 0.3, "max_tokens": max_tokens}
    try:
        body["model"] = _jan_model(client)
    except Exception as e:  # noqa: BLE001
        raise HTTPException(503, f"Jan unreachable or has no model loaded ({e})")
    try:
        # Naming the model loads it; the guard holds off the idle release while
        # the answer is being written.
        if _jan:
            with _jan.using(str(body["model"])):
                r = client.post(
                    f"{JAN_BASE}/chat/completions", json=body, timeout=180.0
                )
        else:
            r = client.post(f"{JAN_BASE}/chat/completions", json=body, timeout=180.0)
    except httpx.RequestError as e:
        raise HTTPException(
            503, f"Jan unreachable at {JAN_BASE} ({type(e).__name__}: {e})"
        )
    if r.status_code != 200:
        raise HTTPException(502, f"Jan returned {r.status_code}: {r.text[:300]}")
    data = r.json()
    try:
        return data["choices"][0]["message"]["content"]
    except (KeyError, IndexError):
        raise HTTPException(
            502, f"Unexpected response shape from Jan: {json.dumps(data)[:300]}"
        )


MAX_MESSAGE_CHARS = 20000


def _course_and_sources(payload: dict) -> tuple[str, list[str]]:
    course = payload.get("course") or ""
    source_ids = payload.get("source_ids") or []
    if not isinstance(course, str):
        raise HTTPException(400, "course must be a folder name")
    if not isinstance(source_ids, list) or not all(
        isinstance(s, str) for s in source_ids
    ):
        raise HTTPException(400, "source_ids must be a list of source names")
    return course, source_ids


def _clean_history(history: object) -> list[dict]:
    """The chat so far, as Jan expects it: user and assistant turns of text."""
    if not isinstance(history, list) or not history:
        raise HTTPException(400, "messages required")
    for m in history:
        if (
            not isinstance(m, dict)
            or m.get("role") not in ("user", "assistant")
            or not isinstance(m.get("content"), str)
        ):
            raise HTTPException(
                400, "each message needs a role (user or assistant) and text"
            )
        if len(m["content"]) > MAX_MESSAGE_CHARS:
            raise HTTPException(
                413,
                f"a message is {len(m['content']):,} characters; the limit is "
                f"{MAX_MESSAGE_CHARS:,}. Put long notes in the course folder instead.",
            )
    return [{"role": m["role"], "content": m["content"]} for m in history]


@app.post("/api/chat")
def chat(payload: dict):
    course, source_ids = _course_and_sources(payload)
    history = _clean_history(payload.get("messages"))
    material = _read_sources(course, source_ids) if course and source_ids else ""
    system = SYSTEM_PROMPT + (
        material
        if material
        else "(no source material selected -- warn the student if that matters for their question.)"
    )
    messages = [{"role": "system", "content": system}] + history
    with httpx.Client() as client:
        reply = _call_jan(client, messages)
    return {"reply": reply}


# ---------------------------------------------------------------- quiz generation via Jan

_JSON_LINE_RE = re.compile(r"^\s*\{.*\}\s*$")


@app.post("/api/quiz")
def quiz(payload: dict):
    course, source_ids = _course_and_sources(payload)
    try:
        count = max(1, min(int(payload.get("count") or 4), 10))
    except (TypeError, ValueError, OverflowError):
        raise HTTPException(400, "count must be a whole number from 1 to 10")
    material = _read_sources(course, source_ids) if course and source_ids else ""
    if not material:
        raise HTTPException(
            400, "select at least one source to generate a grounded quiz from"
        )
    ask = (
        f"Generate exactly {count} NEW practice questions in the JSON-lines format "
        "described in your instructions, testing the material above. Vary the "
        "numbers/specifics so they are not copies of any worked example in the "
        "source text. Output nothing except the JSON lines."
    )
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT + material},
        {"role": "user", "content": ask},
    ]
    with httpx.Client() as client:
        raw = _call_jan(client, messages, max_tokens=1600)

    parsed, rejected = [], 0
    for line in raw.splitlines():
        line = line.strip().strip("`")
        if not line or not _JSON_LINE_RE.match(line):
            if line:
                rejected += 1
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            rejected += 1
            continue
        if not isinstance(row, dict) or not all(
            k in row for k in ("question", "answer")
        ):
            rejected += 1
            continue
        parsed.append(row)

    if parsed and course:
        extra_dir = DATA_DIR / course / "questions"
        extra_dir.mkdir(parents=True, exist_ok=True)
        with (extra_dir / "bank_jan.jsonl").open("a") as fh:
            for row in parsed:
                fh.write(json.dumps(row) + "\n")

    return {
        "questions": parsed,
        "rejected_lines": rejected,
        "raw": raw if not parsed else None,
    }


